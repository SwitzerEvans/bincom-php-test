    //     FROM polling_unit
    //     WHERE polling_unit_number = ?
    // ");
    
    $query = "
        SELECT *
        FROM polling_unit
        WHERE polling_unit_number = ?
    ";
    $stmt = $conn->prepare($query);
    
    $stmt->bind_param("s", $polling_unit_number);
    $stmt->execute();

    $result = $stmt->get_result();
    $polling_unit = $result->fetch_assoc();

    // Get results
    $sql = "
        SELECT party_abbreviation, party_score
        FROM announced_pu_results
        WHERE polling_unit_uniqueid = ?
    ";

    $stmt = $conn->prepare($sql);
    $stmt->bind_param("i", $polling_unit['uniqueid']);
    $stmt->execute();

    $result = $stmt->get_result();

    while ($row = $result->fetch_assoc()) {
        $results[] = $row;
    }
}

